package dao3.pickcat.core.ui.theme

import androidx.compose.ui.unit.dp

/**
 * Shared spacing scale for screens and shared components.
 *
 * Cards are separated by [Md]. Screen edges use [Lg]. Avoid one-off gaps
 * when a standard step fits; consistent rhythm makes nested cards feel
 * related instead of floating independently.
 */
object PickCatSpacing {
    val Xs = 4.dp
    val Sm = 8.dp
    val Md = 12.dp
    val Lg = 16.dp
    val Xl = 24.dp
}
